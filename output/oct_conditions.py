def day(s): x = d(s); return f"{x.day} {MON[x.month]}"
def rng(a, b):
    xa, xb = d(a), d(b)
    if xa == xb: return day(a)
    if xa.month == xb.month: return f"с {xa.day} по {xb.day} {MON[xa.month]}"
    return f"с {day(a)} по {day(b)}"
def plus7(s): x = d(s) + dt.timedelta(days=7); return x
