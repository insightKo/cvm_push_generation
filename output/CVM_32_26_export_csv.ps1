# CVM неделя 32 (03.08-09.08.2026) - выгрузка списков на отправку в CSV
# Каждый список сохраняется отдельным файлом: <номер>_<название>.csv (одна колонка CRM_GUID, без заголовка).
#
# КАК ЗАПУСТИТЬ (на той же машине, где работаешь в SSMS):
# 1. В строке $Server ниже впиши то же имя сервера, что вводишь в SSMS в окне подключения (поле Server name).
# 2. Скопируй этот файл на ту машину (например в D:\).
# 3. Пуск -> набери PowerShell -> Enter, и в синем окне выполни:
#    powershell -ExecutionPolicy Bypass -File "D:\CVM_32_26_export_csv.ps1"
#    (путь поправь на тот, куда положила файл)
# Аутентификация: по умолчанию Windows (-T). Если заходишь в SSMS под SQL-логином,
# в строке bcp замени -T на: -U твой_логин -P твой_пароль

