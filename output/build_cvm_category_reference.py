def word_hit(name, words):
    up = (name or '').upper().replace('Ё', 'Е')
    return any(re.search(r'(?<![А-ЯA-Z0-9])' + re.escape(w.upper().replace('Ё', 'Е')), up) for w in words)


def apply_cut(code, name):
    for inc, exc, target in CUTS[code]:
        if exc and word_hit(name, exc):
            continue
        if not inc or word_hit(name, inc):
            return target
    return UNMAPPED


def main():
    wb = openpyxl.load_workbook(SRC, read_only=True)
    tree = list(wb['Дерево'].iter_rows(values_only=True))[1:]
    cuts_src = list(wb['Разрезы'].iter_rows(values_only=True))[1:]
    prods = list(wb['Товары по полкам'].iter_rows(values_only=True))[1:]

    # 1. категории после чистки
    cats, log, water_codes = {}, [], []
    ext_name = {}
    for g, c, unit, nos, n, share, codes, names, note in tree:
        codes_l = [x.strip() for x in str(codes or '').split(',') if x.strip()]
        names_l = [x.strip() for x in str(names or '').split(';')]
        if len(codes_l) == len(names_l):
            for k, v in zip(codes_l, names_l):
                ext_name.setdefault(k.rstrip('*'), v)
        key = (g, c)
        if key == WATER_SPLIT:
            water_codes = [x.rstrip('*') + '*' for x in codes_l]
            log.append(f'«{c}» убрана: вода только газированная или негазированная — коды режутся по пометке')
            continue
        if key in SKIP:
            log.append(f'«{c}» ({g}) убрана: товары сборного кода — правилами на основные полки')
            continue
        if key in MERGE:
            tg, tc, tu = MERGE[key]
            if (tg, tc) != key:
                log.append(f'«{c}» ({g}) слита в «{tc}» ({tg})' if tc != c else f'«{c}» перенесена из группы «{g}» в «{tg}»')
            if tu and tu != unit:
                log.append(f'«{c}» ({g}): единица {unit} → {tu}')
            key, unit = (tg, tc), (tu or unit)
        elif key in RENAME:
            log.append(f'«{c}» ({g}) переименована в «{RENAME[key]}» — то же имя в другой группе')
            key = (g, RENAME[key])
        if key in cats and (g, c) == key:
            log.append(f'«{c}» ({g}): две строки с одним именем слиты в одну')
        rec = cats.setdefault(key, {'unit': unit, 'noscale': bool(nos), 'n': 0, 'share': 0.0,
                                    'codes': [], 'notes': []})
        if unit and rec['unit'] != unit:
            log.append(f'«{key[1]}»: единица {rec["unit"]} → {unit} при слиянии')
            rec['unit'] = unit
        rec['noscale'] = rec['noscale'] or bool(nos)
        rec['n'] += n or 0
        rec['share'] += share or 0
        rec['codes'] += [x for x in codes_l if x not in rec['codes']]
        if note:
            rec['notes'].append(str(note))
    for k in (WATER_GAZ, WATER_NEGAZ):
        cats[k]['codes'] += water_codes
    for (g, c), rec in cats.items():
        if g == 'Детские товары' and c in KIDS_CLOTHES_NO_SCALE and not rec['noscale']:
            rec['noscale'] = True
            log.append(f'«{c}» ({g}): без шкалы — детская одежда без шкалы (Елена 19.10)')
        if g in ('Детские товары', 'Одежда и обувь') and NO_SCALE_FOOTWEAR.search(c) and not rec['noscale']:
            rec['noscale'] = True
            log.append(f'«{c}» ({g}): без шкалы — обувь без шкалы (решение пачки 8)')

    dup = [n for n, k in collections.Counter(c for _, c in cats).items() if k > 1]
    assert not dup, f'категории с одинаковым названием: {dup}'

    # 2. ID: группы по обороту, категории внутри группы по обороту
    gshare = collections.Counter()
    for (g, _), rec in cats.items():
        gshare[g] += rec['share']
    groups = sorted(gshare, key=lambda g: (g == 'Служебное', -gshare[g], g))
    gid = {g: i + 1 for i, g in enumerate(groups)}
    cid, nxt = {}, 1001
    for g in groups:
        for key in sorted((k for k in cats if k[0] == g), key=lambda k: (-cats[k]['share'], k[1])):
            cid[key] = nxt
            nxt += 1

    # 3. маппинг кодов
    code_rows = []
    all_codes = collections.OrderedDict()
    for key, rec in cats.items():
        for x in rec['codes']:
            all_codes.setdefault(x.rstrip('*'), set()).add(key)
    for r in cuts_src:
        ext_name.setdefault(str(r[0]), r[1])
    for code, keys in all_codes.items():
        if code in BY_PRODUCT:
            method, target = 'по товарам', None
        elif code in CUTS:
            method, target = 'по словам', None
        else:
            assert len(keys) == 1, (code, keys)
            method, target = 'целиком', next(iter(keys))
        code_rows.append((code, ext_name.get(code), method, cid[target] if target else None,
                          target[1] if target else None))
    missing = [t for rules in CUTS.values() for *_, t in rules if t not in cid]
    assert not missing, missing

    # 4. товарный маппинг
    prod_rows, bad = [], []
    for pid, name, src, g, c, how, check in prods:
        if pid in PRODUCT_FIX:
            g, c, how = PRODUCT_FIX[pid]
            check = None
        check = CHECK_DONE.get(check, check)
        if (g, c) == WATER_SPLIT:
            # пометка в названии; без пометки — по метке кода: «вода без пометки» из негазированного кода 61020403
            t = apply_cut('61020403' if src == 'вода без пометки' else '61020201', name)
            g, c = t
            how = f'{how}; без полки «Вода минеральная» — по пометке'
        key = SKIP.get((g, c), (g, c))
        key = MERGE[key][:2] if key in MERGE else (key[0], RENAME.get(key, key[1]))
        if key not in cid:
            bad.append((pid, g, c))
            continue
        prod_rows.append((pid, name, src, cid[key], key[0], key[1],
                          'вручную' if 'вручн' in str(how) or 'провер' in str(how) else 'по названию', how, check))
    assert not bad, bad[:5]

    # проверка правил воды на размеченных вручную товарах воды
    wcheck = collections.Counter()
    for pid, name, src, cat_id, g, c, *_ in prod_rows:
        if src == 'вода без пометки':
            t = apply_cut('61020403', name)
            wcheck['совпало' if t == (g, c) else 'расходится (ручная привязка)'] += 1

    # пересчёт «Товаров» по полной выгрузке I_PRODUCT (если передана): ручная привязка → код целиком → правило слов
    unmapped = collections.Counter()
    if len(sys.argv) > 1:
        manual = {r[0]: r[3] for r in prod_rows}
        whole = {r[0]: r[3] for r in code_rows if r[2] == 'целиком'}
        per_cat = collections.Counter()
        with open(sys.argv[1], encoding='utf-8') as f:
            for row in csv.reader(f):
                if row[0] != 'P':
                    continue
                pid, name, code = int(row[1]), row[2], row[3]
                if pid in manual:
                    k = manual[pid]
                elif code in whole:
                    k = whole[code]
                elif code in CUTS:
                    k = cid[apply_cut(code, name)]
                else:
                    k = cid[UNMAPPED]
                    unmapped['новый код ДИКСИ' if code else 'без кода'] += 1
                if k == cid[UNMAPPED] and code in CUTS:
                    unmapped['правило не нашло полку'] += 1
                if k == cid[UNMAPPED] and code in BY_PRODUCT and pid not in manual:
                    unmapped['новый товар кода «по товарам»'] += 1
                per_cat[k] += 1
        for key, rec in cats.items():
            rec['n'] = per_cat.get(cid[key], 0)

    # 5. запись
    out = openpyxl.Workbook()
    bold = Font(bold=True)

    def sheet(title, head, rows, widths):
        ws = out.create_sheet(title)
        ws.append(head)
        for cell in ws[1]:
            cell.font = bold
            cell.alignment = Alignment(wrap_text=True, vertical='top')
        for row in rows:
            ws.append(list(row))
        for i, w in enumerate(widths):
            ws.column_dimensions[openpyxl.utils.get_column_letter(i + 1)].width = w
        ws.freeze_panes = 'A2'

    out.remove(out.active)
    sheet('Группы', ['ID группы', 'Группа', 'Категорий', 'Доля оборота'],
          [(gid[g], g, sum(1 for k in cats if k[0] == g), round(gshare[g], 6)) for g in groups], [10, 28, 11, 13])
    sheet('Категории', ['ID категории', 'ID группы', 'Группа', 'Категория', 'Единица', 'Без шкалы', 'Статус',
                        'Товаров', 'Доля оборота', 'Ext-коды («*» — делится)', 'Примечание'],
          [(cid[k], gid[k[0]], k[0], k[1], r['unit'], 'да' if r['noscale'] else None, 'активна', r['n'],
            round(r['share'], 6), ', '.join(r['codes']), ' | '.join(r['notes']))
           for k, r in sorted(cats.items(), key=lambda kv: cid[kv[0]])],
          [12, 10, 22, 36, 9, 10, 9, 9, 12, 40, 60])
    sheet('Маппинг кодов', ['Ext-код', 'Ext-название', 'Как относится', 'ID категории', 'Категория'],
          code_rows, [16, 44, 14, 12, 36])
    sheet('Правила разрезов', ['Ext-код', 'Порядок', 'Если в названии любое из', 'И нет ни одного из',
                               'ID категории', 'Категория'],
          [(code, i + 1, ', '.join(inc) or '— всё остальное —', ', '.join(exc) or None, cid[t], t[1])
           for code, rules in CUTS.items() for i, (inc, exc, t) in enumerate(rules)],
          [12, 9, 44, 30, 12, 36])
    sheet('Товарный маппинг', ['ID товара', 'Название', 'Откуда', 'ID категории', 'Группа', 'Категория',
                               'Источник', 'Как отнесено', 'Проверить'],
          prod_rows, [11, 50, 16, 12, 20, 32, 13, 30, 30])
    sheet('Изменения к черновику', ['Что сделано'], [(x,) for x in log], [110])
    out.save(DST)

    print('групп', len(groups), 'категорий', len(cats), 'без шкалы', sum(r['noscale'] for r in cats.values()),
          'единицы', collections.Counter(r['unit'] for r in cats.values()))
    print('кодов', len(code_rows), collections.Counter(r[2] for r in code_rows), 'правил', sum(map(len, CUTS.values())))
    print('товаров', len(prod_rows), 'проверка воды', dict(wcheck), 'несопоставлено', dict(unmapped))
    print('пустые категории', [k[1] for k, r in cats.items() if len(sys.argv) > 1 and not r['n']])
    print('без названия кода', sum(1 for r in code_rows if not r[1]))
    for x in log:
        print(' -', x)


if __name__ == '__main__':
    main()
