select [Итог] = iif(p.FINISH_DATE_AFTER = a.NEW_AFTER, N'по правилу', N'НЕ СОВПАДАЕТ'), [Акций] = count(*)
from #a as a
		inner join I_PROMO as p (nolock)
		on p.ID_PROMO = a.ID_PROMO
		and p.ID_COMPANY = 1
