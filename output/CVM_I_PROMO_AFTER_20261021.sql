set FINISH_DATE_AFTER = a.NEW_AFTER
from I_PROMO as p
		inner join #a as a
		on a.ID_PROMO = p.ID_PROMO
where p.ID_COMPANY = 1
	and p.TYPE_PROMO = N'CVM'
	and p.FINISH_DATE_AFTER = a.OLD_AFTER

