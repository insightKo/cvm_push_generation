def block_for(code):
    if code in BLOCK_NAME:
        return BLOCK_NAME[code]
    if code[:6] in CAT4_BLOCK:
        return CAT4_BLOCK[code[:6]]
    return cat_name.get(code, f'Категория {code}').strip().capitalize()

