-- ============================================================================================
-- CVM_EFFECT_RUN — полный пересчёт эффекта CVM по всем акциям с 01.09.2025 (18.10.2026).
-- Зачем: в отчёт вернулись шесть показателей (ARPU и чеков на клиента — на купивших, 19.10) — клиентов ЦГ → ARPU → средний чек → чеков на клиента → SKU в чеке →
--   цена SKU (ЦГ, КГ, инкремент, «в акцию» и «после»); и ставится процедура с правкой ГКГ от 16.10 (ГКГ — только с
--   первой партии жеребьёвки или если КГ в списке нет): на сервере стоит версия до неё — 23 акции окт–дек 2025
--   посчитаны по архиву прежней ГКГ; 19.10 — при низкой доле КГ контроль из КГ списка (ГКГ без подборки и фильтров отбора
--   несопоставима), внутри слоя давности — полосы ТО «до», чтобы у ЦГ и КГ в слое был одинаковый ТО «до».
-- Порядок:
--   1. CVM_EFFECT_PROC.sql целиком (F5): в витрины I_CVM_EFFECT / I_CVM_EFFECT_CG добавляются колонки шести
--      показателей (строки остаются — портал не пустеет), ставится новая процедура dbo.CVM_EFFECT_TODAY.
--   2. Этот файл — по шагам: выделить блок и выполнить. Ход и время — во вкладке «Сообщения».
-- Что делает файл по объектам:
--   dbo.CVM_EFFECT_TODAY — запуск (одна акция; затем вся история);
--   dbo.I_CVM_EFFECT, dbo.I_CVM_EFFECT_CG — строки акций переписываются процедурой (DELETE + INSERT по акции);
--   больше ничего не меняется и не удаляется.
-- История — только с @stop_at: после 23:30 новые акции не начинаются, чтобы не пересечься с ночным заданием.
-- Не досчиталось за вечер — запустить шаг Б ещё раз: продолжит с акций, посчитанных до установки процедуры.
-- ============================================================================================

USE mci_model
GO

-- ---------- Шаг А. Одна акция: шесть показателей на месте ----------
EXEC dbo.CVM_EFFECT_TODAY @id_promo = 101384;

SELECT [ID], [Канал продаж], [Клиентов ЦГ в акцию]
     , [ARPU в акцию ЦГ, ₽], [ARPU в акцию КГ, ₽], [ARPU в акцию инкр., ₽], [ARPU в акцию инкр., %]
     , [Ср. чек в акцию ЦГ, ₽], [Ср. чек в акцию КГ, ₽], [Ср. чек в акцию инкр., ₽], [Ср. чек в акцию инкр., %]
     , [Чеков на клиента в акцию ЦГ], [Чеков на клиента в акцию КГ], [Чеков на клиента в акцию инкр.], [Чеков на клиента в акцию инкр., %]
     , [SKU в чеке в акцию ЦГ], [SKU в чеке в акцию КГ], [SKU в чеке в акцию инкр.], [SKU в чеке в акцию инкр., %]
     , [Цена SKU в акцию ЦГ, ₽], [Цена SKU в акцию КГ, ₽], [Цена SKU в акцию инкр., ₽], [Цена SKU в акцию инкр., %]
     , [Доп ТО в акцию, ₽]
     -- ARPU и чеков на клиента — на купивших; сверка: ARPU = чеков на клиента × средний чек (у ЦГ и у КГ, до округления ~0)
     , [Сверка ЦГ: ARPU − чеков × ср. чек, ₽] = cast([ARPU в акцию ЦГ, ₽] - [Чеков на клиента в акцию ЦГ] * [Ср. чек в акцию ЦГ, ₽] AS decimal(19, 2))
     , [Сверка КГ: ARPU − чеков × ср. чек, ₽] = cast([ARPU в акцию КГ, ₽] - [Чеков на клиента в акцию КГ] * [Ср. чек в акцию КГ, ₽] AS decimal(19, 2))
FROM dbo.I_CVM_EFFECT (nolock)
WHERE ID_COMPANY = 1 AND [ID] = 101384
ORDER BY CHANNEL_ID;
GO

-- ---------- Шаг Б. Все акции с 01.09.2025: от новых к старым; пересчитываются все, посчитанные до установки
--            процедуры (повторный запуск продолжает с оставшихся). Остановка — сегодня в 23:30 (дата берётся сама:
--            запуск после полуночи остановится сразу, а не через сутки) ----------
DECLARE @left int, @since datetime2(0), @stop datetime2(0) = dateadd(minute, 23 * 60 + 30, CAST(CAST(getdate() AS date) AS datetime2(0)));
SELECT @since = o.modify_date FROM sys.objects AS o (nolock) WHERE o.object_id = OBJECT_ID(N'dbo.CVM_EFFECT_TODAY');
EXEC dbo.CVM_EFFECT_TODAY @date_from = '2025-09-01', @calc_before = @since, @stop_at = @stop, @left = @left OUTPUT;
SELECT [Процедура поставлена] = @since, [Акций осталось пересчитать] = @left;
GO

-- ---------- Шаг В. Итог: общий эффект — без акций «КГ несопоставима» (решение 19.10), они — отдельной строкой ----------
DECLARE @since datetime2(0);
SELECT @since = o.modify_date FROM sys.objects AS o (nolock) WHERE o.object_id = OBJECT_ID(N'dbo.CVM_EFFECT_TODAY');
SELECT [Группа]                = CASE WHEN [КГ несопоставима] = 1 THEN N'КГ несопоставима — вне общего эффекта'
                                      ELSE N'в общем эффекте' END
     , [Акций]                 = count(*)
     , [Без проверки до старта] = sum(CASE WHEN [КГ несопоставима] IS NULL THEN 1 ELSE 0 END)
     , [Пересчитано]           = sum(CASE WHEN [Дата расчета] >= @since THEN 1 ELSE 0 END)
     , [Доп ТО итого, ₽]       = sum([Доп ТО итого, ₽])
     , [Доп ТО итого на всю ЦГ, ₽] = sum([Доп ТО итого на всю ЦГ, ₽])
     , [Скидка всего, ₽]       = sum([Скидка всего, ₽])
     , [PL итого, ₽]           = sum([PL итого, ₽])
     , [PL итого на всю ЦГ, ₽] = sum([PL итого на всю ЦГ, ₽])
FROM dbo.I_CVM_EFFECT (nolock)
WHERE ID_COMPANY = 1
  AND CHANNEL_ID = 0   -- строка «Все каналы»; офлайн и онлайн — CHANNEL_ID 1 и 3
GROUP BY CASE WHEN [КГ несопоставима] = 1 THEN N'КГ несопоставима — вне общего эффекта'
              ELSE N'в общем эффекте' END
ORDER BY 1;
GO
