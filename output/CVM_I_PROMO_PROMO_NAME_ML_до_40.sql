-- CVM · I_PROMO: имя списка для ML до 40 знаков · 19.10.2026
-- Решение Елены 19.10.2026: «PROMO_NAME_ML сделай до сорока символов» (было: название до 20, колонка nvarchar(32) — правило 13.10.2026).
-- Правило: ID_PROMO + '_' + название; всё имя целиком не длиннее 40 знаков. Из названия — без спецсимволов, без служебных слов
--   (активируй, скидка, на, и, в, с, по, от, для, к, за, из, до), без повторов, слова целиком, пока помещаются.
-- Функции dbo.CVM_PROMO_NAME_ML в mci_model нет (проверено 18.10.2026) — имена готовыми строками.
-- Что меняется:
--   dbo.I_PROMO.PROMO_NAME_ML — тип nvarchar(32) → nvarchar(40) (только расширение, данные не трогает);
--   dbo.I_PROMO — UPDATE одной колонки PROMO_NAME_ML у 21 акций (101393–101443): пустые заполняются, имена по старому правилу удлиняются.
-- Что не меняется: имя, поправленное руками (101413), имена, которые и так укладываются (101416, 101420, 101425, 101432–101438, 101444),
--   строка, которую успели поменять после 19.10 (UPDATE идёт только при старом значении), тестовые 100000–100019, остальные колонки, списки I_PROMO_OFFER.
-- Запускать целиком (F5) в mci_model. Повторный запуск ничего не меняет.

use mci_model
GO

if col_length('dbo.I_PROMO', 'PROMO_NAME_ML') is null
	throw 50001, N'В dbo.I_PROMO нет колонки PROMO_NAME_ML — сначала CVM_I_PROMO_PROMO_NAME_ML.sql. Ничего не изменено', 1;
GO

-- col_length в байтах: nvarchar(40) = 80; -1 у nvarchar(max) — не трогаем
if col_length('dbo.I_PROMO', 'PROMO_NAME_ML') between 1 and 79
	alter table dbo.I_PROMO alter column PROMO_NAME_ML nvarchar(40) null
GO

update p
set PROMO_NAME_ML = v.NEW_NAME
from dbo.I_PROMO p
join (values
	  (101393, null, N'101393_Купон 50р любую покупку')
	, (101394, null, N'101394_Вина купон 100р 7 дней')
	, (101395, null, N'101395_Крепкий алкоголь купон 100р 7')
	, (101396, null, N'101396_Пиво купон 100р 7 дней')
	, (101397, null, N'101397_Коммуникация детские категории')
	, (101398, null, N'101398_Коммуникация ПП')
	, (101399, null, N'101399_Коммуникация готовой еде')
	, (101400, null, N'101400_Коммуникация товары животных')
	, (101401, null, N'101401_Тематическая рассылка вино')
	, (101402, null, N'101402_Тематическая рассылка пиво')
	, (101403, null, N'101403_10 готовый кофе 12 утра')
	, (101412, N'101412_20 мандарины', N'101412_20 мандарины апельсины лимоны')
	, (101415, N'101415_50 кешбэка товары', N'101415_50 кешбэка товары женской гигиены')
	, (101417, N'101417_20 кешбэка готовую', N'101417_20 кешбэка готовую еду кулинарию')
	, (101419, N'101419_20 бумажные влажные', N'101419_20 бумажные влажные салфетки')
	, (101426, null, N'101426_Дарим 100 монет неделю')
	, (101427, null, N'101427_300р чек 3000р')
	, (101428, null, N'101428_Отток 50 кешбэка дням')
	, (101439, N'101439_50 кешбэка выпечку', N'101439_50 кешбэка выпечку собственного')
	, (101441, N'101441_50 кешбэка домашние', N'101441_50 кешбэка домашние тапочки')
	, (101443, N'101443_50 кешбэка конфеты', N'101443_50 кешбэка конфеты коробках')
) v (ID_PROMO, OLD_NAME, NEW_NAME) on v.ID_PROMO = p.ID_PROMO
where p.ID_COMPANY = 1
  and (   (v.OLD_NAME is null and nullif(ltrim(rtrim(p.PROMO_NAME_ML)), N'') is null)
       or p.PROMO_NAME_ML = v.OLD_NAME)

select @@rowcount as UPDATED_ROWS   -- ожидается 21 при первом запуске, 0 при повторном
GO

-- контроль: действующие акции и их имена для ML
select ID_PROMO, START_DATE, FINISH_DATE, PROMO_NAME, PROMO_NAME_ML, len(PROMO_NAME_ML) as LEN_ML
from dbo.I_PROMO with (nolock)
where ID_COMPANY = 1
  and FINISH_DATE >= '20261012'
  and ID_PROMO >= 101000
order by ID_PROMO
GO
