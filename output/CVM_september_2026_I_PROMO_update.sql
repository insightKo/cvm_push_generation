-- CVM сентябрь 2026 · дельта к месячному скрипту CVM_september_2026_I_PROMO.sql
-- Причина: алкогольные slip-купоны 101360, 101361, 101362 на неделе 36 не запустились.
-- Вместо них с 09.09 идёт slip-купон 50 р. на любую покупку — как августовская 101332.
-- Аудитория 101391 — Активные, Новые, Спящие, Отток, поэтому ID_SEGMENT = 2 «Отток»
-- и окно истории -52*3 недели (как у августовской 101333).
-- Отдельного купона 100 р. на покупку от 900 р. в сентябре нет.
-- Прогонять сверху вниз. Блок 1 обязательно раньше блока 2: в I_PROMO_OFFER лежит ссылка на акцию.


-- ==================================================================================
-- БЛОК 1. ПРОВЕРКА ПЕРЕД УДАЛЕНИЕМ — что именно уберём
-- ==================================================================================

select *
from I_PROMO (nolock)
where ID_PROMO in (101360, 101361, 101362)
GO

select ID_PROMO
		, [Клиентов в списке] = count(distinct ID_CONTACT)
		, [Из них на отправку] = count(distinct case when CONTROL_GROUP = 0 then ID_CONTACT end)
from I_PROMO_OFFER (nolock)
where ID_PROMO in (101360, 101361, 101362)
group by ID_PROMO
GO


-- ==================================================================================
-- БЛОК 2. УДАЛЕНИЕ АЛКОГОЛЬНЫХ SLIP-КУПОНОВ 101360–101362
-- ==================================================================================

DELETE FROM I_PROMO_OFFER
where ID_PROMO in (101360, 101361, 101362)
GO

DELETE FROM I_PROMO
where ID_PROMO in (101360, 101361, 101362)
GO


-- ==================================================================================
-- БЛОК 3. НОВАЯ АКЦИЯ 101391 · Купон 50р. на любую покупку · slip · выдача 09.09–30.09
-- Аудитория: Активные, Новые, Спящие, Отток.
-- ==================================================================================

DECLARE @d date = '2026-09-09'
DECLARE @fd date = '2026-09-30'

INSERT INTO [mci_model].[dbo].[I_PROMO]
values (
	  DATEADD(week,-52*3, @d)
	  , DATEADD(day,-1, @d)
	  , @d
	  , @fd
	  , 101391
	  , 'Купон 50р. на любую покупку'
	  , dateadd(day,+1,@fd)
	  ,	dateadd(day,+7,@fd)
	  , 'SLIP'
	  , 'Отток'
	  , 2
	  , NULL
	  , 'Купон'
	  , 5
	  , 4
	  , NULL
	  , NULL
	  , 'CVM'
	  , 1
	  )
GO


-- ==================================================================================
-- БЛОК 4. КОНТРОЛЬ ПОСЛЕ ПРОГОНА
-- Ожидание: 101360–101362 не найдены ни в одной таблице, 101391 заведена.
-- ==================================================================================

select [Проверка] = N'Осталось строк в I_PROMO по 101360–101362', [Строк] = count(*)
from I_PROMO (nolock)
where ID_PROMO in (101360, 101361, 101362)
union all
select N'Осталось строк в I_PROMO_OFFER по 101360–101362', count(*)
from I_PROMO_OFFER (nolock)
where ID_PROMO in (101360, 101361, 101362)
union all
select N'Заведена 101391 в I_PROMO', count(*)
from I_PROMO (nolock)
where ID_PROMO = 101391
GO
