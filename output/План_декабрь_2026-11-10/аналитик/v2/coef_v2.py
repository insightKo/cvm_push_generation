R = pd.read_pickle('fam_res.pkl'); U = pd.read_pickle('fam_units.pkl'); A = pd.read_pickle('A.pkl').set_index('ID')
SIG = ('Значимо', 'Сильно', 'Очень')
rows = []


def dur_txt(ids):
    d = A.loc[ids].dur
    return f'{int(d.min())}' if d.min() == d.max() else f'{int(d.min())}–{int(d.max())}'


def period_txt(ids):
    s = A.loc[ids]
    return f"{s.start.min():%d.%m.%Y}–{s.fin.max():%d.%m.%Y}"


def add(fam, seg, cell, ids, post, lo, hi, raw, raw_se, unit, fit, com, tag=''):
    p = A.loc[ids]
    disc = p.disc.sum() / p.N.sum()
    pl = (post * 0.3 - disc) / 1.15 if np.isfinite(post) else np.nan
    nsig = int(p.sig.astype(str).str.startswith(SIG).sum())
    src = sorted(set(p.src))
    z = post / ((hi - lo) / 3.92) if np.isfinite(post) and hi > lo else np.nan
    pre = [str(i) for i in ids if A.loc[i, 'prelim']]
    if pre:
        com = (com + '; ' if com else '') + 'предварительные: ' + ', '.join(pre)
    snap = [str(i) for i in ids if A.loc[i, 'src'] == 'снимок 06.11']
    if snap:
        com = (com + '; ' if com else '') + 'ошибка у ' + ', '.join(snap) + ' восстановлена (в снимке нет ДИ)'
    rows.append({'семейство': fam, 'сегмент / список': seg, 'ячейка': cell, 'единица': unit, 'длительность, дн.': dur_txt(ids), 'период фактов': period_txt(ids),
                 '₽ на клиента (прогнозный, после сжатия)': round(post, 2) if np.isfinite(post) else '',
                 'ДИ 95 % от': round(lo, 2) if np.isfinite(lo) else '', 'ДИ 95 % до': round(hi, 2) if np.isfinite(hi) else '',
                 '₽ на клиента сырой': round(raw, 2), 'ошибка сырого': round(raw_se, 2),
                 'скидка ₽ на клиента': round(disc, 2), 'PL ₽ на клиента': round(pl, 2) if np.isfinite(pl) else '',
                 'клиентов ЦГ в фактах, тыс.': round(p.N.sum() / 1e3, 1), 'n акций': len(ids), 'ID аналогов': ', '.join(str(i) for i in ids),
                 'значимость': (sig_label(z) + '; ' if np.isfinite(z) else '') + f'значимых акций {nsig} из {len(ids)}',
                 'источник': ' + '.join(src), 'годится в прогноз (да/нет/осторожно)': fit, 'комментарий': com})


def fit_rule(post, lo, raw, n, N, lifted):
    if post <= 0 or raw <= 0: return 'нет'
    f = 'да' if (lo > 0 and n >= 2) else 'осторожно'
    if f == 'да' and (lifted or N < 100000): f = 'осторожно'
    return f


def from_cells(key, fam, unit, segf, extra=None):
    C, F, par, u = R[key]
    for _, c in C.sort_values('post', ascending=False).iterrows():
        g = u[u.kc == c.kc]; ids = list(g.ID)
        raw, rse = c.r, np.sqrt(c.v0)
        lifted = c.post > raw + 1
        com = []
        if lifted: com.append(f'оценка поднята к среднему: свой факт {raw:.2f}')
        if c.post < raw - 1: com.append(f'сжато к среднему семейства (вес своей оценки {c.get("Bc", c.get("B", 1)):.2f})')
        small = [str(i) for i in ids if A.loc[i, 'N'] < 20000]
        if small: com.append('малые списки < 20 тыс. (ошибка на клиента 40–110 ₽): ' + ', '.join(small))
        if extra: com += extra(c, g)
        add(fam, segf(c, g), c.kc, ids, c.post, c.lo, c.hi, raw, rse, unit, fit_rule(c.post, c.lo, raw, len(ids), c.N, lifted), '; '.join(com))


