def reason(r):
    if r['Нет КГ'] is True or pd.isna(r.all3):
        return 'нет КГ в оценке'
    if r['КГ несопоставима'] is True:
        return 'КГ несопоставима'
    if r['КГ несопоставима'] is None or (isinstance(r['КГ несопоставима'], float) and np.isnan(r['КГ несопоставима'])):
        return 'проверка «до старта» не проведена'
    if r['cov'] < 0.5:
        return f'в оценке {r['cov']:.1%} ЦГ'
    return ''


