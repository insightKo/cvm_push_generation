num = lambda s: float(s.replace(' ', '').replace(',', '.'))


def fam(r):
    m, n = str(r['Механика']), str(r['Название'])
    nl = n.lower()
    rub = re.search(r'(\d+)\s*(?:р\.?|руб|rub|r\b|монет|балл|бонус)', nl)
    pct = re.search(r'(\d+)\s*%', nl)
    thr = re.search(r'(?:от|с|более|чек от|с чека)\s*(\d[\d ]*)\s*(?:р|$|\b)', nl)
    R = num(rub.group(1)) if rub else np.nan
    T = num(thr.group(1)) if thr else np.nan
    Pc = num(pct.group(1)) if pct else np.nan
    if m == 'Скидка X р. на чек':
        if T == R: T = np.nan
        return 'Скидка N р. на чек от X', R, T
    if m == 'Кешбэк X монет за покупку':
        return 'Вернём N р. монетами с чека от X', R, T
    if m == 'Целевые монеты на покупку от X р.':
        return 'Монеты N на чек от X (целевые)', R, T
    if m == 'Начисление монет':
        return 'Начисление N монет без порога', R, np.nan
    if m == 'Купон X р. на покупку':
        if 'на следующую покупку' in nl: T = np.nan
        return 'Купон N р. на покупку (слип/пуш)', R, T
    if m in ('Скидка X% на чек', 'Купон-скидка X% на покупку', 'VIP-скидка'):
        return 'Скидка X% на чек', Pc, T
    if m == 'Кешбэк X% с чека':
        return 'Кешбэк X% с чека', Pc, T
    if m in ('Кешбэк X% с покупки категории', 'Кэшбек'):
        return 'Кешбэк X% на категорию', Pc, np.nan
    if m == 'Кешбэк X р. с покупки категории':
        return 'Кешбэк N монет за категорию', R, np.nan
    if m in ('Скидка X% на категорию', 'Купон-скидка X% на категорию'):
        if 'подборка' in nl or 'промокод' in nl and r.ch == 'онлайн':
            return 'Скидка % на категорию / подборка с промокодом', Pc, np.nan
        return 'Скидка X% на категорию', Pc, np.nan
    if m == 'Подарок за 1 ₽':
        return 'Подарок за 1 ₽ от чека X', np.nan, T
    if m == 'Каскад от суммы чека':
        return 'Каскад от суммы чека', np.nan, np.nan
    if m == 'Каскад на частоту':
        return 'Каскад на частоту', np.nan, np.nan
    if m == 'Бесплатная доставка':
        return 'Бесплатная доставка', np.nan, np.nan
    if m == 'Купон на спеццену':
        return 'Купон на спеццену', np.nan, np.nan
    if m == 'Коммуникация':
        if 'баланс' in nl or 'списание бонусов' in nl:
            return 'Коммуникация: баланс монет', np.nan, np.nan
        if 'кэшбек 50%' in nl:
            return 'Кешбэк X% на категорию', 50.0, np.nan
        return 'Коммуникация: тематическая / подборка', np.nan, np.nan
    return 'прочее: ' + m, np.nan, np.nan


