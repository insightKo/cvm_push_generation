def pooled(ids):
    """Σ Доп ТО итого на всю ЦГ / Σ клиентов ЦГ и Σ скидки / Σ клиентов ЦГ по аналогам (витрина, «Все каналы»)."""
    rows = [EFF[i] for i in ids if i in EFF and EFF[i]['Доп ТО итого на всю ЦГ, ₽'] is not None and not EFF[i]['КГ несопоставима']]
    n = sum(r['Клиентов ЦГ'] for r in rows)
    eff = sum(r['Доп ТО итого на всю ЦГ, ₽'] for r in rows)
    disc = sum(r['Скидка всего, ₽'] or 0 for r in rows)
    return eff / n, disc / n, rows


