def healthy_target(name):
    up = (name or '').upper().replace('C', 'С')          # латинская C в начале названий
    for pat, cat in HEALTHY_RULES:
        if re.search(pat, up):
            return cat
    return None


def apply(moves, products_by_cat, tree):
    """moves — список переносов; products_by_cat — {категория: [[id, название, код], ...]}; tree — {полка: запись}."""
    for rec in tree.values():                      # группы вида «Бакалея + …» / «Хлеб и выпечка → Бакалея» из предложений
        g = rec['group']
        rec['group'] = g.split('→')[-1].strip() if '→' in g else g.split('+')[0].strip()
    for g, c, u in NEW_SHELVES:
        tree.setdefault(c, {'group': g, 'category': c, 'unit': u, 'no_scale': False, 'new': True})
    out = []
    for m in moves:
        # 4 — нет: майонезные соусы остаются в «Майонезе»
        if m['from'] == 'Майонез' and m['to'] == 'Соусы':
            continue
        # 7а — яичные продукты за кг
        if m['to'] == 'Несопоставленные' and re.search(r'ЯИЧН', (m['name'] or '').upper()):
            m = dict(m, to='Яичные продукты', reason='яичный продукт за кг — своя полка (решение 19.10)')
        # 1, 2, 3, 5, 6, 8 — да; остальные сомнительные применяются как предложено
        if not m['sure']:
            m = dict(m, sure=True, reason=m['reason'] + ' (решено 19.10)')
        out.append(m)

    # роспуск «Здорового питания»: что осталось на полке после переносов и что пришло — по правилам
    moved_out = {m['product_id'] for m in out if m['from'] == HEALTHY}
    staying = [(i, n) for i, n, _ in products_by_cat.get(HEALTHY, []) if i not in moved_out]
    unresolved = []
    for i, n in staying:
        t = healthy_target(n)
        if t is None:
            unresolved.append((i, n))
            t = 'Несопоставленные'
        out.append({'product_id': i, 'name': n, 'from': HEALTHY, 'to': t, 'source': 'проверка', 'sure': t != 'Несопоставленные',
                    'reason': '«Здоровое питание» распускается — товар на свою полку (решение 19.10)'})
    for m in out:
        if m['to'] == HEALTHY:
            t = healthy_target(m['name']) or 'Несопоставленные'
            m.update(to=t, reason=m['reason'] + '; «Здоровое питание» распускается')
    return out, unresolved


# Ответы Елены на вопросы круга 2 (product_id → категория); пока ответа нет — перенос не применяется
ROUND_ANSWERS = {
    # вопрос 2 — да
    15092: 'Йогурты питьевые',
    255886: 'Расчёски и щётки для волос',
    158022: 'Дезодоранты женские', 154124: 'Дезодоранты женские', 160823: 'Дезодоранты женские',
    289898: 'Сало и шпик',
    61646: 'Сырьё для производства',
}
# вопрос 1 — а: все остальные вопросы круга 2 (крупные фасовки без пометки, «ПР-ВО» мелкие, вишня на развес, концентрат) — в сырьё
ROUND_DEFAULT_ANSWER = 'Сырьё для производства'


def apply_rounds(moves, rounds):
    """Итоги двух кругов проверки коммерческим менеджером: confirm → to1, change → to2, reject — без переноса,
    ask — только по ответу Елены (ROUND_ANSWERS)."""
    by_pid = {m['product_id']: m for m in moves}
    pending = []
    for r in rounds:
        if r['verdict'] == 'confirm':
            to = r['to1']
        elif r['verdict'] == 'change':
            to = r['to2']
        elif r['verdict'] == 'ask':
            to = ROUND_ANSWERS.get(r['product_id'], ROUND_DEFAULT_ANSWER)
        else:
            if r['verdict'] == 'ask':
                pending.append(r)
            continue
        reason = 'проверка коммерческим менеджером: ' + (r['reason2'] or r['reason1'])
        m = by_pid.get(r['product_id'])
        if m:
            m.update(to=to, reason=reason, sure=True)
        else:
            m = {'product_id': r['product_id'], 'name': r['name'], 'from': r['from'], 'to': to,
                 'source': 'проверка', 'sure': True, 'reason': reason}
            moves.append(m)
            by_pid[r['product_id']] = m
    return [m for m in moves if m['from'] != m['to']], pending
