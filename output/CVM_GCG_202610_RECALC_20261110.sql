-- Отчёт ГКГ за октябрь 2026 — пересчёт после перезаливки чеков (просьба Елены 10.11.2026).
-- Перезаливка: загрузка 07.11 01:00 – 08.11 15:21, период чеков 01.08–06.11.2026; обработка чеков заданием
-- «MCI Regular update» закончена 09.11 19:53 (шаг INSERT I_CHECK_DELTA). Октябрь в витрине был посчитан 01.11 10:47 — до перезаливки.
-- dbo.gcg_report @YM = 202610 заменяет октябрь целиком в I_GCG_REPORT и I_GCG_REPORT_LAYER (одна транзакция; пустой расчёт
-- октябрь не стирает — процедура падает). Методика и партии ГКГ не меняются.
-- Повтор безопасен: если октябрь уже посчитан после конца обработки чеков — пропуск.
SET NOCOUNT ON
SET XACT_ABORT ON
GO
USE mci_model
GO
IF EXISTS (SELECT 1 FROM dbo.I_GCG_REPORT (nolock)
           WHERE YEAR_MONTH = 202610 AND [Источник] = N'процедура gcg_report' AND [Дата расчёта] >= '2026-11-09T19:54:00')
    PRINT N'Октябрь уже пересчитан после перезаливки — пропуск';
ELSE
    EXEC dbo.gcg_report @YM = 202610;

SELECT YEAR_MONTH, [Сегмент], [Доп ТО р], [ДИ 95% низ], [ДИ 95% верх], [Значимо]
     , [Клиентов ЦГ], [Клиентов ГКГ], [ТО ЦГ], [ТО ГКГ], [ТО ЦГ ДО], [ТО ГКГ ДО], [KOEF]
     , [Данные с], [Данные по], [Полный месяц], [Дата расчёта]
FROM dbo.I_GCG_REPORT (nolock)
WHERE YEAR_MONTH = 202610
ORDER BY SEGMENT;
GO
