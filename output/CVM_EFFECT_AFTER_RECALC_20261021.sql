-- с какого момента акция считается пересчитанной по новому периоду: окончание скрипта правки в журнале обменника
DECLARE @since datetime2(0) = (SELECT max(FINISHED) FROM dbo.CVM_API_JOB_LOG (nolock)
                               WHERE JOB = N'CVM_I_PROMO_AFTER_20261021' AND STATUS = 'ok');
IF @since IS NULL SET @since = '2026-10-21T14:40:00';   -- правку ставили не через обменник: выложена в 14:44, считать от 14:40

DECLARE @stop datetime2(0) = dateadd(minute, 23 * 60 + 30, CAST(CAST(getdate() AS date) AS datetime2(0)));
DECLARE @id int, @n int = 0, @msg nvarchar(300);

DECLARE c CURSOR LOCAL FAST_FORWARD FOR
    SELECT r.ID_PROMO
    FROM #r AS r
    WHERE NOT EXISTS (SELECT 1 FROM dbo.I_CVM_EFFECT AS e (nolock)
                      WHERE e.ID_COMPANY = 1 AND e.[ID] = r.ID_PROMO AND e.[Дата расчета] >= @since)
    ORDER BY r.ID_PROMO DESC;
OPEN c;
FETCH NEXT FROM c INTO @id;
WHILE @@FETCH_STATUS = 0
BEGIN
    IF sysdatetime() >= @stop
    BEGIN
        RAISERROR(N'23:30 — остановка. Запустить файл ещё раз: продолжит с оставшихся', 0, 1) WITH NOWAIT;
        BREAK;
    END
    SET @msg = concat(N'пересчёт ', @id, N' · старт ', convert(varchar(19), sysdatetime(), 120));
    RAISERROR(@msg, 0, 1) WITH NOWAIT;
    EXEC dbo.CVM_EFFECT_TODAY @id_promo = @id;
    SET @n += 1;
    FETCH NEXT FROM c INTO @id;
END
CLOSE c;
DEALLOCATE c;

SELECT [Пересчитано в этом запуске] = @n
     , [Осталось] = (SELECT count(*) FROM #r AS r
                     WHERE NOT EXISTS (SELECT 1 FROM dbo.I_CVM_EFFECT AS e (nolock)
                                       WHERE e.ID_COMPANY = 1 AND e.[ID] = r.ID_PROMO AND e.[Дата расчета] >= @since));

-- итог по пересчитанным: эффект «после» и итого
SELECT e.[ID], e.CHANNEL_ID, e.[Дата расчета], e.[Доп ТО итого, ₽], e.[Значимость итого]
FROM dbo.I_CVM_EFFECT AS e (nolock)
JOIN #r AS r ON r.ID_PROMO = e.[ID]
WHERE e.ID_COMPANY = 1 AND e.[Дата расчета] >= @since
ORDER BY e.[ID], e.CHANNEL_ID;

