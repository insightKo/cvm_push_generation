    блок 3 изменился       -> ГКГ перенарезали (в gcg_extract.sql отбор идёт
                              через newid() и заливка truncate+insert);
                              состав контроля обязан быть постоянным.
    ничего не изменилось,
    а цифры разные         -> дело в nolock: прогон попал на ETL и прочитал
                              недописанные данные. Убрать nolock из расчёта
                              или запускать в окно без заливки.
