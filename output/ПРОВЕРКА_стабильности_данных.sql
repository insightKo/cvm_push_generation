  Прогнать В РАЗНЫЕ ДНИ и сравнить строки между собой. Что изменилось —
  то и есть причина. Сам расчёт эффекта от текущей даты не зависит:
  все границы периодов в нём зашиты жёстко.

  Читается БЕЗ nolock — намеренно: если запрос ждёт блокировок, значит
  в этот момент идёт заливка, и любой прогон с nolock прочитает
  недописанные данные.
==============================================================================*/

SET NOCOUNT ON;
DECLARE @idc int = 1;
DECLARE @dt_from date = '2026-07-01';
DECLARE @dt_to   date = '2026-08-01';

-- 1. Отпечаток ИЮЛЬСКИХ данных. Меняется -> данные догружаются/корректируются.
select [Проверка]      = '1. Чеки июля'
     , [Строк]         = count(*)
     , [Клиентов]      = count(distinct ID_CONTACT)
     , [Оборот, руб]   = sum(cast(COST_DISCOUNT as float))
     , [Мин дата]      = min(DATA)
     , [Макс дата]     = max(DATA)
from I_CHECKHEADER
where ID_COMPANY = @idc and ID_CONTACT <> 0
  and DATA >= @dt_from and DATA < @dt_to;

-- 2. Отпечаток ПРЕПЕРИОДА (6 недель до июля) — та же проверка для активных.
select [Проверка]    = '2. Чеки препериода 20.05-30.06'
     , [Строк]       = count(*)
     , [Оборот, руб] = sum(cast(COST_DISCOUNT as float))
from I_CHECKHEADER
where ID_COMPANY = @idc and ID_CONTACT <> 0
  and DATA >= dateadd(week, -6, @dt_from) and DATA < @dt_from;

-- 3. Отпечаток ГКГ. Меняется -> контрольную группу перенарезали,
--    и результаты разных дней несопоставимы в принципе.
select [Проверка]        = '3. Состав ГКГ'
     , [Строк]           = count(*)
     , [Контактов]       = count(distinct ID_CONTACT)
     , [Контрольная сумма ID] = sum(cast(ID_CONTACT as float))
     , [Мин ID]          = min(ID_CONTACT)
     , [Макс ID]         = max(ID_CONTACT)
from I_GLOBAL_CG
where ID_COMPANY = @idc and CONTROL_GROUP = 1;

-- 4. Насколько свежа таблица чеков в целом.
select [Проверка]           = '4. Глубина данных'
     , [Макс дата в чеках]  = max(DATA)
     , [Сегодня]            = cast(getdate() as date)
     , [Отставание, дней]   = datediff(day, max(DATA), cast(getdate() as date))
from I_CHECKHEADER
where ID_COMPANY = @idc;

