-- защита: все 40 шапок должны быть в I_PROMO (организация 1), иначе ничего не меняем
declare @missing int = (select count(*) from @m as m where not exists (select 1 from dbo.I_PROMO as p (nolock) where p.ID_PROMO = m.ID_PROMO and p.ID_COMPANY = 1))
if @missing > 0
begin
	raiserror(N'I_PROMO лайфстайл-сегменты: в I_PROMO нет %d из 40 шапок — ничего не изменено', 16, 1, @missing)
	return
end

-- ДО (в журнал задания)
declare @todo int = (select count(*) from dbo.I_PROMO as p (nolock) join @m as m on m.ID_PROMO = p.ID_PROMO
                     where p.ID_COMPANY = 1 and (p.ID_SEGMENT is null or p.SEGMENT is null or p.ID_SEGMENT <> m.ID_SEGMENT or p.SEGMENT <> m.SEGMENT collate database_default))
if @todo = 0
begin
	raiserror(N'I_PROMO лайфстайл-сегменты: все 40 акций уже с кластерными сегментами — ничего не изменено', 10, 1)
	return
end

update p
   set p.SEGMENT = m.SEGMENT
     , p.ID_SEGMENT = m.ID_SEGMENT
from dbo.I_PROMO as p
join @m as m on m.ID_PROMO = p.ID_PROMO
where p.ID_COMPANY = 1
