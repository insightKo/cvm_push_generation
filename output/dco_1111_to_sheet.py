def first_empty(v):
    last = max(i for i, r in enumerate(v, start=1) if any(str(x).strip() for x in r))
    return last + 1


def main():
    bdir = Path(sys.argv[1]); bdir.mkdir(parents=True, exist_ok=True)
    assert len(P) == 26 and [p[0] for p in P] == list(range(101497, 101523))
    ss = sc.get_spreadsheet()
    wo, wp = ss.worksheet(sc.SHEET_CVM_OFFLINE), ss.worksheet(sc.SHEET_PUSH)
    vo = wo.get_all_values(value_render_option="FORMULA")
    vp = wp.get_all_values(value_render_option="FORMULA")
    stamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    (bdir / f"backup_cvm_offline_{stamp}.json").write_text(json.dumps(vo, ensure_ascii=False), encoding="utf-8")
    (bdir / f"backup_push_{stamp}.json").write_text(json.dumps(vp, ensure_ascii=False), encoding="utf-8")
    nums = {str(n) for n, *_ in P}
    assert not [r for r in vo[1:] if str(r[1]).split("_")[0].strip() in nums], "номера уже есть в CVM offline"
    assert not [r for r in vp[1:] if len(r) > 11 and str(r[11]).strip() in nums], "номера уже есть в PUSH"
    assert vo[0][36] == "Ограничения и комментарии" and vo[0][13] == "Примерное количество клиентов"
    assert vp[0][11] == "Номер промо" and vp[0][17] == "Экран - ссылка"

    o0 = first_empty(vo)
    rows_o = []
    for n, name, ml, cnt, gold, kind in P:
        r = [""] * 37
        r[0], r[1], r[2], r[3] = "нет", n, name, "Активные, Новые"
        r[4], r[5], r[6], r[7], r[8], r[9], r[10] = 2026, 11, 46, "ср", DAY, DAY, "PUSH"
        r[12], r[13], r[25], r[36] = ml, cnt, "Коммуникация", NOTE.format(kind=kind)
        rows_o.append(r)
    wo.update(range_name=f"A{o0}:AK{o0 + len(rows_o) - 1}", values=rows_o, value_input_option="USER_ENTERED")

    p0 = first_empty(vp)
    rows_p = []
    for k, (n, name, ml, cnt, gold, kind) in enumerate(P):
        i = p0 + k
        rows_p.append([
            f"=VLOOKUP(L{i};'CVM offline'!B:LO;3;FALSE)", f"=VLOOKUP(L{i};'CVM offline'!B:LO;10;FALSE)",
            f"=VLOOKUP(L{i};'CVM offline'!B:LO;2;FALSE)", f"=YEAR(H{i})", f"=MONTH(H{i})", f"=WEEKNUM(H{i};2)",
            f"=VLOOKUP(WEEKDAY(H{i};2);'данные'!A:B;2;FALSE)", DAY, TIME_11,
            f"=VLOOKUP(L{i};'CVM offline'!B:N;13;false)", "минус фрод", n, 1,
            "", f"=LEN(N{i})", "", f"=LEN(P{i})", f"dixyapp://app/product?gold_erp_id={gold}", "", ""])
    wp.update(range_name=f"A{p0}:T{p0 + len(rows_p) - 1}", values=rows_p, value_input_option="USER_ENTERED")

    chk_o = wo.get_values(f"B{o0}:N{o0 + 25}")
    chk_p = wp.get_values(f"A{p0}:R{p0 + 25}")
    print("бэкап", stamp)
    print(f"CVM offline строки {o0}–{o0 + 25}:", chk_o[0][:3], "…", chk_o[-1][:3], "| клиентов", sum(int(str(r[12]).replace(' ', '').replace('\xa0', '') or 0) for r in chk_o))
